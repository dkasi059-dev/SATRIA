    "## Cara kerja atribusi lab (inti perbaikan)\n",
    "\n",
    "Setiap lab punya **tag** yang diturunkan dari judulnya, misalnya:\n",
    "\n",
    "| Lab | Tag yang wajib dibuktikan |\n",
    "|---|---|\n",
    "| SQL injection in WHERE clause | `sql_injection`, `where` |\n",
    "| Visible error-based SQL injection | `sql_injection`, `error_based` |\n",
    "| JWT bypass via unverified signature | `jwt`, `jwt_unverified` |\n",
    "| Basic clickjacking | `clickjacking` |\n",
    "\n",
    "Sebuah temuan hanya memetakan ke lab bila **semua** tag lab ada pada temuan itu\n",
    "(`lab.tags ⊆ finding.tags`). Temuan juga menyimpan `target` dan `host`, lalu\n",
    "diperiksa ulang oleh *scope guard* sebelum dilaporkan.\n",
    "\n",
    "Status yang mungkin:\n",
    "\n",
    "- `TERDETEKSI` — bukti lengkap ada pada target ini.\n",
    "- `KANDIDAT` — indikasi kuat, butuh satu langkah verifikasi (mis. ubah parameter).\n",
    "- `BELUM TERBUKTI` — permukaan ada, tetapi bukti untuk lab ini tidak ditemukan.\n",
    "- `TIDAK RELEVAN` — prasyarat teknis tidak ada (mis. tidak ada upload/JWT/XML).\n",
    "\n",
    "Lab yang berbagi tag identik dilaporkan sebagai **kelompok** agar tidak ada klaim\n",
